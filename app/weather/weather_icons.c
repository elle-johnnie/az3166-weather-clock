const uint16_t* weather_icon(int code, int is_day)
{
    switch (code)
    {
        case 0:  // clear
        case 1:  // mainly clear
            return is_day ? ICON_SUN : ICON_MOON;
        case 2:  // partly cloudy
            return is_day ? ICON_PARTLY_DAY : ICON_PARTLY_NIGHT;
        case 45: // fog
        case 48: // depositing rime fog
            return ICON_FOG;
        case 51: // drizzle
        case 53:
        case 55:
            return ICON_DRIZZLE;
        case 56: // freezing drizzle
        case 57:
        case 66: // freezing rain
        case 67:
            return ICON_SLEET;
        case 61: // rain
        case 63:
        case 65:
        case 80: // rain showers
        case 81:
        case 82:
            return ICON_RAIN;
        case 71: // snow
        case 73:
        case 75:
        case 77: // snow grains
        case 85: // snow showers
        case 86:
            return ICON_SNOW;
        case 95: // thunderstorm
        case 96: // thunderstorm with hail
        case 99:
            return ICON_STORM;
        case 3:  // overcast
        default:
            return ICON_CLOUD;
    }
}

void weather_icon_draw(const uint16_t* icon, int x, int y)
{
    for (int row = 0; row < 16; row++)
    {
        for (int col = 0; col < 16; col++)
        {
            if (icon[row] & (0x8000 >> col))
            {
                ssd1306_DrawPixel(x + col, y + row, White);
            }
        }
    }
}
